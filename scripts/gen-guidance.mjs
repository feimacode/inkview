// Writes every generated guidance file from packages/inkview/src/guidance (the single source):
//   plugin/skills/inkview/SKILL.md, the instructions block in docs/chatgpt-app.md,
//   and the plugin version. `--check` exits 1 instead of writing when anything differs.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { pathToFileURL } from "node:url";

const check = process.argv.includes("--check");
mkdirSync("dist-test", { recursive: true });
await build({
  entryPoints: ["packages/inkview/src/guidance/index.ts"],
  outfile: "dist-test/guidance.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  packages: "external",
  logLevel: "warning",
});
const g = await import(pathToFileURL("dist-test/guidance.mjs").href + `?t=${Date.now()}`);
const pkg = JSON.parse(readFileSync("packages/inkview/package.json", "utf8"));

const START = "<!-- guidance:start (generated by npm run gen:guidance, do not edit) -->";
const END = "<!-- guidance:end -->";
const chatgptPath = "docs/chatgpt-app.md";
const chatgpt = readFileSync(chatgptPath, "utf8");
const [before, rest] = chatgpt.split(START);
const after = rest.split(END)[1];

const pluginPath = "plugin/.claude-plugin/plugin.json";
const plugin = JSON.parse(readFileSync(pluginPath, "utf8"));
plugin.version = pkg.version;

const outputs = {
  "plugin/skills/inkview/SKILL.md": g.skillMarkdown(),
  [chatgptPath]: `${before}${START}\n\n\`\`\`text\n${g.chatgptInstructions()}\n\`\`\`\n\n${END}${after}`,
  [pluginPath]: JSON.stringify(plugin, null, 2) + "\n",
};

let stale = 0;
for (const [path, content] of Object.entries(outputs)) {
  let current = "";
  try { current = readFileSync(path, "utf8"); } catch {}
  if (current === content) continue;
  if (check) { console.error(`✗ ${path} is out of date: run npm run gen:guidance`); stale++; }
  else { writeFileSync(path, content); console.log(`wrote ${path}`); }
}
if (check && !stale) console.log("✓ generated guidance is up to date");
process.exit(stale ? 1 : 0);
