// Checks every TypeScript snippet in docs/sdk.md and README.md against the SDK
// types, so the documentation cannot drift from the API. Import lines written in
// the docs are stripped and the names come from the preamble below.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const FILES = ["docs/sdk.md", "README.md"];
const OUT = "dist-test/docs-snippets";

const preamble = `// Generated by scripts/docs-snippets.mjs. Do not edit.
import { McpServer } from "@modelcontextprotocol/server";
import { StdioServerTransport } from "@modelcontextprotocol/server/stdio";
import { registerAppTool } from "@modelcontextprotocol/ext-apps/server";
import {
  DEFAULT_APP_URI,
  inkview,
  inkviewToolMeta,
  registerInkview,
  showChart,
  showComparison,
  showDocument,
  showEntityCard,
  showForm,
  showItinerary,
  showListings,
  showMap,
  showProducts,
  showProfileCard,
  showProfiles,
  showResults,
  showTable,
  showTasks,
  showTimeline,
} from "../../packages/sdk/src/index.js";
`;

const snippets = [];
for (const file of FILES) {
  const text = readFileSync(file, "utf8");
  for (const match of text.matchAll(/```ts(?:cript)?\n([\s\S]*?)```/g)) {
    const code = match[1]
      .replace(/^import .*;\s*$/gm, "")
      .trim();
    snippets.push({ file, code });
  }
}
if (!snippets.length) throw new Error(`no TypeScript snippets found in ${FILES.join(" or ")}`);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
snippets.forEach((snippet, i) => {
  const name = `snippet-${i + 1}.ts`;
  writeFileSync(`${OUT}/${name}`, `${preamble}\n// From ${snippet.file}\n${snippet.code}\n\nexport {};\n`);
});
writeFileSync(
  `${OUT}/tsconfig.json`,
  `${JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        module: "NodeNext",
        moduleResolution: "NodeNext",
        strict: true,
        skipLibCheck: true,
        noEmit: true,
        resolveJsonModule: true,
        types: ["node"],
      },
      include: ["snippet-*.ts", "../../src/env.d.ts"],
    },
    null,
    2,
  )}\n`,
);

execFileSync(process.execPath, ["node_modules/typescript/bin/tsc", "-p", OUT], { stdio: "inherit" });
console.log(`Checked ${snippets.length} documentation snippet(s).`);
